// =============================================================================
// 8. RESULT TYPES
// =============================================================================

/**
 * Result of autodoc_init
 */
export interface InitResult {
  success: boolean;
  /** Created files */
  createdFiles: string[];
  /** Work plan for AI */
  workPlan: {
    totalSections: number;
    highPriority: AutoDocTodo[];
    mediumPriority: AutoDocTodo[];
    lowPriority: AutoDocTodo[];
  };
  /** Error message if failed */
  error?: string;
}

/**
 * Result of autodoc_save
 */
export interface SaveResult {
  success: boolean;
  /** Saved document ID */
  docId?: string;
  /** Extracted references */
  extractedRefs?: number;
  /** Validation warnings */
  warnings?: string[];
  /** Error message if failed */
  error?: string;
}

/**
 * Result of autodoc_validate
 */
export interface ValidateResult {
  /** Total references checked */
  totalRefs: number;
  /** Valid references */
  validRefs: number;
  /** Broken references */
  brokenRefs: Array<{
    refId: string;
    sourceFile: string;
    targetId: string;
    error: string;
  }>;
  /** Fixed references (if fixBrokenRefs=true) */
  fixedRefs?: number;
}
