/**
 * Detect generated clients that consume the API
 */
function detectConsumers(
  codeEntities: Entity[],
  swaggerEndpoints: SwaggerEndpoint[],
  swaggerSpecs: Entity[],
): { consumers: SwaggerCodeLink[]; markers: string[]; configs: string[] } {
  const consumers: SwaggerCodeLink[] = [];
  const foundMarkers: string[] = [];
  const foundConfigs: string[] = [];

  // Detect codegen configs from entities (these are parsed from package.json scripts, file entities, etc.)
  for (const entity of codeEntities) {
    const entityName = entity.name.toLowerCase();
    const filePath = entity.filePath.toLowerCase();

    // Check for codegen config files
    for (const config of CODEGEN_CONFIGS) {
      if (entityName === config.configFile || filePath.endsWith(`/${config.configFile}`)) {
        foundConfigs.push(config.configFile);
      }
    }

    // Check for codegen scripts in package.json
    if (entity.metadata?.["scriptCommand"]) {
      const cmd = String(entity.metadata["scriptCommand"]).toLowerCase();
      if (
        cmd.includes("openapi-generator") ||
        cmd.includes("nswag") ||
        cmd.includes("autorest") ||
        cmd.includes("refitter") ||
        cmd.includes("ng-openapi-gen") ||
        cmd.includes("swagger-codegen")
      ) {
        foundConfigs.push(`script:${entity.name}`);
      }
    }
  }

  // Find generated files by markers in entity metadata
  const generatedFiles = new Set<string>();
  for (const entity of codeEntities) {
    if (entity.metadata?.["isGenerated"] || entity.metadata?.["autoGenerated"]) {
      generatedFiles.add(entity.filePath);
    }

    // Check entity name patterns typical for generated clients
    const name = entity.name;
    if ((name.endsWith("Client") || name.endsWith("Service") || name.endsWith("Api")) && isLikelyGenerated(entity)) {
      generatedFiles.add(entity.filePath);

      // Try to match generated methods to swagger endpoints
      const swaggerFile = swaggerSpecs[0]?.filePath;
      if (swaggerFile) {
        for (const endpoint of swaggerEndpoints) {
          // Match by operation ID or method name similarity
          if (
            endpoint.operationId &&
            (name.includes(endpoint.operationId) ||
              entity.name.toLowerCase().includes(endpoint.operationId.toLowerCase()))
          ) {
            consumers.push({
              swaggerEntityName: endpoint.entityName,
              codeEntityName: entity.name,
              codeFilePath: entity.filePath,
              swaggerFilePath: swaggerFile,
              linkType: "consumes_api",
              confidence: 0.7,
              evidence: [`Operation ID match: ${endpoint.operationId}`, `Generated client pattern: ${name}`],
            });
            foundMarkers.push(`operationId:${endpoint.operationId}`);
          }
        }
      }
    }
  }

  return { consumers, markers: foundMarkers, configs: foundConfigs };
}

/**
 * Check if an entity is likely auto-generated
 */
function isLikelyGenerated(entity: Entity): boolean {
  // Check metadata flags
  if (entity.metadata?.["isGenerated"] || entity.metadata?.["autoGenerated"]) return true;

  // Check file path patterns
  const path = entity.filePath.toLowerCase();
  if (
    path.includes("/generated/") ||
    path.includes("/gen/") ||
    path.includes("/auto-generated/") ||
    path.includes("/__generated__/")
  ) {
    return true;
  }

  return false;
}

