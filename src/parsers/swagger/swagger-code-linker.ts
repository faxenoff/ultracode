/**
 * Swagger Code Linker
 *
 * Links swagger/OpenAPI specifications to code entities (controllers, generated clients, types).
 * Follows the pattern from src/parsers/ngrx/builders.ts.
 *
 * Detection strategies:
 * 1. Producers: Controllers/routes that create the API (NestJS, Express, Spring Boot, .NET)
 * 2. Consumers: Generated clients (openapi-generator, NSwag, Autorest, Refitter, ng-openapi-gen)
 * 3. Schema↔Type matching: Links swagger schemas to code types by name/properties
 */

import { log } from "../../logging/index.js";
import type { Entity } from "../../types/storage.js";
import { RelationType } from "../../types/storage.js";
import type {
  CodegenConfig,
  CodeRoute,
  ProducerPattern,
  SwaggerAnalysis,
  SwaggerCodeLink,
  SwaggerEndpoint,
  SwaggerRelationship,
} from "./types.js";

