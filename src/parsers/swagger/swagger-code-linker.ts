/**
 * Analyze swagger↔code links from graph entities
 *
 * @param entities All entities from the graph
 * @returns SwaggerAnalysis with detected links
 */
export function analyzeSwaggerCodeLinks(entities: Entity[]): SwaggerAnalysis {
  const analysis: SwaggerAnalysis = {
    producers: [],
    consumers: [],
    generatedTypes: [],
    generatedFileMarkers: [],
    codegenConfigs: [],
  };

  // Separate swagger entities from code entities
  const swaggerEndpoints: SwaggerEndpoint[] = [];
  const swaggerSchemas: Entity[] = [];
  const swaggerSpecs: Entity[] = [];
  const codeEntities: Entity[] = [];

  for (const entity of entities) {
    const swaggerType = entity.metadata?.["swaggerType"] as string | undefined;

    if (swaggerType === "endpoint") {
      swaggerEndpoints.push({
        httpMethod: (entity.metadata?.["httpMethod"] as string) || "",
        path: (entity.metadata?.["path"] as string) || "",
        ...((entity.metadata?.["operationId"] as string)
          ? { operationId: entity.metadata["operationId"] as string }
          : {}),
        entityName: entity.name,
        filePath: entity.filePath,
      });
    } else if (swaggerType === "schema") {
      swaggerSchemas.push(entity);
    } else if (swaggerType === "api_spec") {
      swaggerSpecs.push(entity);
    } else if (!entity.metadata?.["isApiContract"]) {
      codeEntities.push(entity);
    }
  }

  // Skip if no swagger entities
  if (swaggerEndpoints.length === 0 && swaggerSchemas.length === 0) {
    return analysis;
  }

  log.i("SWAGGER_LINKER", "analyzing", {
    endpoints: swaggerEndpoints.length,
    schemas: swaggerSchemas.length,
    codeEntities: codeEntities.length,
  });

  // 1. Detect producers (controllers that create the API)
  const producers = detectProducers(codeEntities, swaggerEndpoints);
  analysis.producers = producers;

  // 2. Detect consumers (generated clients)
  const { consumers, markers, configs } = detectConsumers(codeEntities, swaggerEndpoints, swaggerSpecs);
  analysis.consumers = consumers;
  analysis.generatedFileMarkers = markers;
  analysis.codegenConfigs = configs;

  // 3. Match schemas to types
  const generatedTypes = matchSchemasToTypes(swaggerSchemas, codeEntities);
  analysis.generatedTypes = generatedTypes;

  log.i("SWAGGER_LINKER", "analysis_done", {
    producers: analysis.producers.length,
    consumers: analysis.consumers.length,
    generatedTypes: analysis.generatedTypes.length,
    configs: analysis.codegenConfigs.length,
  });

  return analysis;
}

/**
 * Build graph relationships from swagger analysis
 */
export function buildSwaggerRelationships(analysis: SwaggerAnalysis): SwaggerRelationship[] {
  const relationships: SwaggerRelationship[] = [];

  for (const link of analysis.producers) {
    relationships.push({
      fromName: link.codeEntityName,
      toName: link.swaggerEntityName,
      type: RelationType.PRODUCES_API,
      fromFile: link.codeFilePath,
      toFile: link.swaggerFilePath,
      metadata: {
        confidence: link.confidence,
        evidence: link.evidence,
        context: "controller produces API endpoint",
      },
    });
  }

  for (const link of analysis.consumers) {
    relationships.push({
      fromName: link.codeEntityName,
      toName: link.swaggerEntityName,
      type: RelationType.CONSUMES_API,
      fromFile: link.codeFilePath,
      toFile: link.swaggerFilePath,
      metadata: {
        confidence: link.confidence,
        evidence: link.evidence,
        context: "generated client consumes API endpoint",
      },
    });
  }

  for (const link of analysis.generatedTypes) {
    relationships.push({
      fromName: link.codeEntityName,
      toName: link.swaggerEntityName,
      type: RelationType.GENERATED_FROM,
      fromFile: link.codeFilePath,
      toFile: link.swaggerFilePath,
      metadata: {
        confidence: link.confidence,
        evidence: link.evidence,
        schemaName: link.swaggerEntityName,
        context: "type generated from swagger schema",
      },
    });
  }

  return relationships;
}

