// SCHEMA ↔ TYPE MATCHING
// =============================================================================

/**
 * Match swagger schemas to code types
 */
function matchSchemasToTypes(swaggerSchemas: Entity[], codeEntities: Entity[]): SwaggerCodeLink[] {
  const links: SwaggerCodeLink[] = [];

  // Collect code types (interfaces, types, classes that could be DTOs)
  const codeTypes = codeEntities.filter((e) => e.type === "interface" || e.type === "type" || e.type === "class");

  for (const schema of swaggerSchemas) {
    const schemaName = schema.name;
    const schemaProps = extractSchemaPropertyNames(schema);

    let bestMatch: {
      entity: Entity;
      confidence: number;
      evidence: string[];
    } | null = null;

    for (const codeType of codeTypes) {
      const evidence: string[] = [];
      let confidence = 0;

      // 1. Exact name match
      if (codeType.name === schemaName || codeType.name.split(".").pop() === schemaName) {
        confidence += 0.6;
        evidence.push(`Exact name match: ${schemaName}`);
      } else {
        // 2. Name match without suffix
        const strippedName = stripTypeSuffix(codeType.name.split(".").pop() || codeType.name);
        if (strippedName === schemaName) {
          confidence += 0.4;
          evidence.push(`Name match without suffix: ${codeType.name} → ${schemaName}`);
        } else {
          continue; // No name match, skip
        }
      }

      // 3. Property comparison (if both have properties)
      if (schemaProps.length > 0) {
        const codeProps = extractCodePropertyNames(codeType);
        if (codeProps.length > 0) {
          const overlap = schemaProps.filter((sp) => codeProps.includes(sp));
          const propScore = overlap.length / Math.max(schemaProps.length, 1);
          if (propScore >= 0.7) {
            confidence += 0.3;
            evidence.push(
              `Property overlap: ${overlap.length}/${schemaProps.length} (${(propScore * 100).toFixed(0)}%)`,
            );
          } else if (propScore >= 0.3) {
            confidence += 0.1;
            evidence.push(`Partial property overlap: ${overlap.length}/${schemaProps.length}`);
          }
        }
      }

      // Check if code type is generated
      if (isLikelyGenerated(codeType)) {
        confidence += 0.1;
        evidence.push("File in generated path");
      }

      if (confidence > (bestMatch?.confidence ?? 0)) {
        bestMatch = { entity: codeType, confidence: Math.min(1, confidence), evidence };
      }
    }

    if (bestMatch && bestMatch.confidence >= 0.4) {
      links.push({
        swaggerEntityName: schemaName,
        codeEntityName: bestMatch.entity.name,
        codeFilePath: bestMatch.entity.filePath,
        swaggerFilePath: schema.filePath,
        linkType: "generated_from",
        confidence: bestMatch.confidence,
        evidence: bestMatch.evidence,
      });
    }
  }

  return links;
}

/**
 * Extract property names from a swagger schema entity
 */
function extractSchemaPropertyNames(schema: Entity): string[] {
  const props = schema.metadata?.["properties"];
  if (!Array.isArray(props)) return [];
  return props.map((p: { name?: string }) => p.name).filter((n): n is string => typeof n === "string");
}

/**
 * Extract property names from a code type entity
 */
function extractCodePropertyNames(entity: Entity): string[] {
  // Check parameters (for interfaces/types with listed fields)
  if (entity.metadata?.["parameters"] && Array.isArray(entity.metadata["parameters"])) {
    return entity.metadata["parameters"]
      .map((p: { name?: string }) => p.name)
      .filter((n): n is string => typeof n === "string");
  }

  // Check properties metadata
  if (entity.metadata?.["properties"] && Array.isArray(entity.metadata["properties"])) {
    return entity.metadata["properties"]
      .map((p: { name?: string }) => p.name)
      .filter((n): n is string => typeof n === "string");
  }

  return [];
}

/**
 * Strip common type suffixes for name matching
 */
function stripTypeSuffix(name: string): string {
  for (const suffix of TYPE_SUFFIXES) {
    if (name.endsWith(suffix) && name.length > suffix.length) {
      return name.slice(0, -suffix.length);
    }
  }
  return name;
}

