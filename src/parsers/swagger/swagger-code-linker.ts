/**
 * Detect controllers/routes that produce the API described in swagger
 */
function detectProducers(codeEntities: Entity[], swaggerEndpoints: SwaggerEndpoint[]): SwaggerCodeLink[] {
  const links: SwaggerCodeLink[] = [];
  if (swaggerEndpoints.length === 0) return links;

  // Extract routes from code entities
  const codeRoutes = extractCodeRoutes(codeEntities);

  // Match code routes to swagger endpoints
  for (const route of codeRoutes) {
    const match = findEndpointMatch(route, swaggerEndpoints);
    if (match) {
      links.push({
        swaggerEntityName: match.endpoint.entityName,
        codeEntityName: route.entityName,
        codeFilePath: route.filePath,
        swaggerFilePath: match.endpoint.filePath,
        linkType: "produces_api",
        confidence: match.confidence,
        evidence: match.evidence,
      });
    }
  }

  return links;
}

/**
 * Extract route information from code entities by analyzing decorators
 */
function extractCodeRoutes(entities: Entity[]): CodeRoute[] {
  const routes: CodeRoute[] = [];

  // Build a map of controller prefixes by file
  const controllerPrefixes = new Map<string, string>();

  for (const entity of entities) {
    if (!entity.metadata?.["decorators"]) continue;
    const decorators = entity.metadata["decorators"] as Array<{ name: string; arguments?: string[] }>;

    for (const pattern of PRODUCER_PATTERNS) {
      // Check for controller decorators
      const controllerDec = decorators.find((d) => pattern.controllerDecorators.includes(d.name));
      if (controllerDec) {
        const prefix = controllerDec.arguments?.[0]?.replace(/['"]/g, "") || "";
        controllerPrefixes.set(entity.filePath, prefix);
      }

      // Check for route decorators
      for (const dec of decorators) {
        const routeDecName = pattern.routeDecorators.find((rd) => rd === dec.name);
        if (routeDecName) {
          const httpMethod = extractHttpMethodFromDecorator(routeDecName, pattern.framework);
          const routePath = dec.arguments?.[0]?.replace(/['"]/g, "") || "";
          const prefix = controllerPrefixes.get(entity.filePath) || "";
          const fullPath = normalizePath(prefix, routePath);

          if (httpMethod) {
            routes.push({
              httpMethod,
              path: fullPath,
              entityName: entity.name,
              filePath: entity.filePath,
              controllerPrefix: prefix,
            });
          }
        }
      }
    }
  }

  return routes;
}

/**
 * Extract HTTP method from decorator name
 */
function extractHttpMethodFromDecorator(decoratorName: string, _framework: string): string | null {
  const lowerName = decoratorName.toLowerCase();

  // Direct method decorators
  if (lowerName.startsWith("get") || lowerName === "httpget") return "GET";
  if (lowerName.startsWith("post") || lowerName === "httppost") return "POST";
  if (lowerName.startsWith("put") || lowerName === "httpput") return "PUT";
  if (lowerName.startsWith("patch") || lowerName === "httppatch") return "PATCH";
  if (lowerName.startsWith("delete") || lowerName === "httpdelete") return "DELETE";
  if (lowerName === "options") return "OPTIONS";
  if (lowerName === "head") return "HEAD";

  // Spring Boot @RequestMapping needs explicit method
  if (lowerName === "requestmapping") return null; // Ambiguous, skip

  return null;
}

/**
 * Find a matching swagger endpoint for a code route
 */
function findEndpointMatch(
  route: CodeRoute,
  endpoints: SwaggerEndpoint[],
): { endpoint: SwaggerEndpoint; confidence: number; evidence: string[] } | null {
  let bestMatch: { endpoint: SwaggerEndpoint; confidence: number; evidence: string[] } | null = null;

  for (const endpoint of endpoints) {
    const evidence: string[] = [];
    let confidence = 0;

    // Match HTTP method
    if (route.httpMethod === endpoint.httpMethod) {
      confidence += 0.4;
      evidence.push(`HTTP method match: ${route.httpMethod}`);
    } else {
      continue; // Skip if method doesn't match
    }

    // Match path
    const pathScore = compareEndpointPaths(route.path, endpoint.path);
    if (pathScore > 0) {
      confidence += pathScore * 0.6;
      evidence.push(`Path match (${(pathScore * 100).toFixed(0)}%): ${route.path} ↔ ${endpoint.path}`);
    } else {
      continue; // Skip if path doesn't match at all
    }

    if (confidence > (bestMatch?.confidence ?? 0)) {
      bestMatch = { endpoint, confidence: Math.min(1, confidence), evidence };
    }
  }

  return bestMatch && bestMatch.confidence >= 0.5 ? bestMatch : null;
}

/**
 * Compare two endpoint paths, returning a score 0-1
 */
function compareEndpointPaths(codePath: string, swaggerPath: string): number {
  const normCode = normalizeEndpointPath(codePath);
  const normSwagger = normalizeEndpointPath(swaggerPath);

  if (normCode === normSwagger) return 1.0;

  // Compare segments
  const codeSegments = normCode.split("/").filter(Boolean);
  const swaggerSegments = normSwagger.split("/").filter(Boolean);

  if (codeSegments.length !== swaggerSegments.length) return 0;

  let matchCount = 0;
  for (let i = 0; i < codeSegments.length; i++) {
    const cs = codeSegments[i]!;
    const ss = swaggerSegments[i]!;

    if (cs === ss) {
      matchCount++;
    } else if (isPathParam(cs) && isPathParam(ss)) {
      matchCount++; // Both are parameters
    } else {
      return 0; // Structural mismatch
    }
  }

  return matchCount / codeSegments.length;
}

/**
 * Normalize endpoint path for comparison
 * - Strips leading/trailing slashes
 * - Converts {id} to :id and vice versa to a common form
 */
function normalizeEndpointPath(path: string): string {
  return path
    .replace(/^\/|\/$/g, "") // Strip leading/trailing slashes
    .replace(/\{(\w+)\}/g, ":$1") // {id} → :id
    .toLowerCase();
}

/**
 * Check if a path segment is a parameter
 */
function isPathParam(segment: string): boolean {
  return segment.startsWith(":") || segment.startsWith("{");
}

/**
 * Normalize and join controller prefix and route path
 */
function normalizePath(prefix: string, routePath: string): string {
  const parts = [prefix, routePath].filter(Boolean);
  const joined = parts.join("/").replace(/\/+/g, "/");
  return joined.startsWith("/") ? joined : `/${joined}`;
}

