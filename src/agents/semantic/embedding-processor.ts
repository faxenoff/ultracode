/**
 * Check if a file path matches any exclude pattern
 */
export function shouldExcludeFromEmbedding(filePath: string): boolean {
  const normalizedPath = filePath.replace(/\\/g, "/");
  for (const pattern of EMBEDDING_EXCLUDE_PATTERNS) {
    if (normalizedPath.includes(pattern)) {
      return true;
    }
  }
  return false;
}

/**
 * Determine if an entity is too trivial to embed.
 *
 * Trivial entities add noise to the vector index and waste generation time.
 * We skip them when they satisfy ALL of:
 *   - Very short body (≤2 lines of code)
 *   - No outgoing calls (pure assignment / return)
 *   - No control-flow branches or loops
 *   - No JSDoc / inline description
 *
 * Typical examples: bare getters, setters, single-return delegators.
 * If ANY signal of semantic value is present the entity is kept.
 */
export function isTrivialEntity(entity: ParsedEntity): boolean {
  const loc = entity.complexity?.linesOfCode ?? 0;
  if (loc === 0) return false; // Unknown size — keep to be safe

  const hasCalls = (entity.calls?.length ?? 0) > 0;
  const cf = entity.controlFlow;
  const hasFlow = (cf?.branches?.length ?? 0) + (cf?.loops?.length ?? 0) + (cf?.exceptions?.length ?? 0) > 0;
  const hasDoc = !!entity.documentation?.description;

  if (hasCalls || hasFlow || hasDoc) return false;

  // Pure trivial: ≤2 LOC, no outgoing calls, no flow, no docs
  return loc <= 2;
}

/**
 * Build enhanced text for embedding from entity data
 */
export function buildEmbeddingText(entity: ParsedEntity, code: string): string {
  const parts: string[] = [];

  // Header
  const header = `${entity.name ?? ""} ${entity.type ?? ""} ${entity.signature ?? ""}`.trim();
  if (header) parts.push(header);

  // Add documentation if available (improves semantic search by description)
  if (entity.documentation?.description) {
    parts.push(`description: ${entity.documentation.description}`);
  }

  // Add call information (enables "find functions that call X" queries)
  if (entity.calls && entity.calls.length > 0) {
    const callsToProcess = entity.calls.length > 20 ? entity.calls.slice(0, 20) : entity.calls;
    const callParts: string[] = [];
    for (const c of callsToProcess) {
      if (!c) continue;
      callParts.push(c.target ? `${c.target}.${c.name || ""}` : c.name || "");
    }
    if (callParts.length > 0) {
      parts.push(`calls: ${callParts.join(", ")}`);
    }
  }

  // Add complexity info (enables "find complex functions" queries)
  if (entity.complexity) {
    const cx = entity.complexity;
    if (cx.cyclomatic > 5 || cx.cognitive > 10) {
      parts.push(`complexity: cyclomatic=${cx.cyclomatic} cognitive=${cx.cognitive}`);
    }
  }

  // Add control flow summary (enables "find functions with try-catch" queries)
  if (entity.controlFlow) {
    const cf = entity.controlFlow;
    const flowParts: string[] = [];
    if (cf.branches?.length > 0) flowParts.push(`branches=${cf.branches.length}`);
    if (cf.loops?.length > 0) flowParts.push(`loops=${cf.loops.length}`);
    if (cf.exceptions?.length > 0) flowParts.push(`exceptions=${cf.exceptions.length}`);
    if (cf.awaits?.length > 0) flowParts.push(`awaits=${cf.awaits.length}`);
    if (flowParts.length > 0) {
      parts.push(`flow: ${flowParts.join(", ")}`);
    }
  }

  // Add return type for better type-based search
  if (entity.returnType) {
    parts.push(`returns: ${entity.returnType}`);
  }

  // Add parameter types for signature-based search
  if (entity.parameters && entity.parameters.length > 0) {
    const paramParts: string[] = [];
    for (const p of entity.parameters) {
      if (p.type && paramParts.length < 10) {
        paramParts.push(`${p.name}:${p.type}`);
      }
    }
    if (paramParts.length > 0) {
      parts.push(`params: ${paramParts.join(", ")}`);
    }
  }

  // Add the code
  if (code) {
    parts.push(code);
  }

  return parts.join("\n").trim();
}

/**
 * Build vector embedding metadata from entity
 */
export function buildVectorMetadata(entity: ParsedEntity, modelName: string): Record<string, unknown> {
  const metadata: Record<string, unknown> = {
    path: entity.filePath ?? entity.path ?? "",
    type: entity.type,
    name: entity.name,
    language: entity.language ?? undefined,
    entityId: entity.id ?? undefined,
    start: entity.location?.start?.index ?? undefined,
    end: entity.location?.end?.index ?? undefined,
    model: modelName,
  };

  // Add complexity metrics (enables filtering by complexity)
  if (entity.complexity) {
    metadata["cyclomatic"] = entity.complexity.cyclomatic;
    metadata["cognitive"] = entity.complexity.cognitive;
    metadata["linesOfCode"] = entity.complexity.linesOfCode;
    metadata["nestingDepth"] = entity.complexity.nestingDepth;
  }

  // Add call count (enables "find functions with many calls" queries)
  if (entity.calls?.length) {
    metadata["callCount"] = entity.calls.length;
    metadata["hasAsyncCalls"] = entity.calls.some((c) => c.isAwait);
  }

  // Add control flow flags (enables filtering)
  if (entity.controlFlow) {
    const cf = entity.controlFlow;
    metadata["hasBranches"] = (cf.branches?.length || 0) > 0;
    metadata["hasLoops"] = (cf.loops?.length || 0) > 0;
    metadata["hasExceptions"] = (cf.exceptions?.length || 0) > 0;
    metadata["hasAwaits"] = (cf.awaits?.length || 0) > 0;
    metadata["branchCount"] = cf.branches?.length || 0;
    metadata["loopCount"] = cf.loops?.length || 0;
    metadata["returnCount"] = cf.returns?.length || 0;
  }

  // Add documentation flag (enables "find documented functions" queries)
  if (entity.documentation) {
    metadata["hasDocumentation"] = true;
    metadata["hasParams"] = (entity.documentation.params?.length || 0) > 0;
    metadata["hasExamples"] = (entity.documentation.examples?.length || 0) > 0;
    metadata["isDeprecated"] = !!entity.documentation.deprecated;
  }

  // Add return type for type-based filtering
  if (entity.returnType) {
    metadata["returnType"] = entity.returnType;
  }

  // Add parameter count
  if (entity.parameters?.length) {
    metadata["paramCount"] = entity.parameters.length;
  }

  return metadata;
}

