/**
 * Context for embedding processing
 * Allows dependency injection from SemanticAgent
 */
export interface EmbeddingProcessorContext {
  // Core components
  embeddingGen: EmbeddingGenerator;
  vectorStore: VectorStore;
  globalCache: GlobalEmbeddingCache | null;

  // Configuration
  embeddingDim: number;
  embeddingBatchSize: number;
  twoPhaseMode: boolean;

  // State
  dumpBatchIndex: number;
  semanticMetrics: SemanticMetrics;

  // Mutex for thread safety
  embeddingMutex: Promise<void>;
  setEmbeddingMutex: (p: Promise<void>) => void;

  // Callbacks
  onDumpBatchIndexIncrement: () => void;
  onMetricsUpdate: (count: number) => void;
  onVectorsStoredUpdate: () => Promise<void>;
}

