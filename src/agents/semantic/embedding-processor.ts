/**
 * Embedding Processor Module
 *
 * Handles entity embedding generation and storage.
 * Extracted from semantic-agent.ts for better modularity.
 *
 * Main responsibilities:
 * - Filter entities for embedding generation
 * - Handle pre-generated embeddings from workers
 * - Build embedding texts with enhanced metadata
 * - Deduplicate texts and check caches
 * - Generate embeddings in batches
 * - Store embeddings in vector store
 */

import { log } from "../../logging/index.js";
import type { EmbeddingGenerator } from "../../semantic/embedding-generator.js";
import type { GlobalEmbeddingCache } from "../../semantic/global-embedding-cache.js";
import type { VectorStore } from "../../semantic/vector-store.js";
import type { ParsedEntity } from "../../types/parser.js";
import type { SemanticMetrics, VectorEmbedding } from "../../types/semantic.js";
import { hashText } from "../../utils/fast-hash.js";

/**
 * ParsedEntity with pre-generated embedding from worker
 */
interface ParsedEntityWithEmbedding extends ParsedEntity {
  embeddingBase64?: string;
  embeddingText?: string;
}

// =============================================================================
// CONSTANTS
// =============================================================================

/**
 * Path patterns to EXCLUDE from embedding generation only
 * (entities are still indexed for LSP/navigation)
 *
 * Machine-generated code is indexed for import resolution, call graphs, etc.
 * but excluded from semantic search embeddings because:
 * - High volume (thousands of entities per file)
 * - Low value for semantic search (auto-generated code patterns)
 * - Significantly increases generation time
 */
export const EMBEDDING_EXCLUDE_PATTERNS = [
  "src/generated/", // ANTLR parsers (Java20Parser.ts, RustParser.ts, etc.)
  "/autogenerated/", // Common auto-generated code directory
  "/node_modules/", // Third-party dependencies
  "/__generated__/", // GraphQL / OpenAPI codegen output
  "/.cache/", // Build/tooling caches
  "/dist/", // Compiled output
];

