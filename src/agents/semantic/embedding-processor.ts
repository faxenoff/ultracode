/**
 * Process entities with pre-generated embeddings from workers
 */
export async function processPreGeneratedEmbeddings(
  entities: ParsedEntity[],
  ctx: Pick<EmbeddingProcessorContext, "vectorStore" | "onMetricsUpdate">,
  modelName: string,
): Promise<{ processed: number; failed: ParsedEntity[] }> {
  const failedEntities: ParsedEntity[] = [];
  const vectorEmbeddings: VectorEmbedding[] = [];

  for (const entity of entities) {
    const e = entity as ParsedEntityWithEmbedding;
    try {
      // Decode base64 to Float32Array
      const binaryData = Buffer.from(e.embeddingBase64!, "base64");
      const vector = new Float32Array(binaryData.buffer, binaryData.byteOffset, binaryData.length / 4);

      // Build stable ID
      const stableId = e.id
        ? `ent:${e.id}`
        : `doc:${hashText(`${e.filePath ?? ""}|${e.type}|${e.name ?? "anon"}|${modelName}`).slice(0, 24)}`;

      vectorEmbeddings.push({
        id: stableId,
        content: e.embeddingText ?? `${e.name ?? ""} ${e.type ?? ""}`.trim(),
        vector,
        metadata: buildVectorMetadata(e, modelName),
        createdAt: Date.now(),
      });
    } catch (error) {
      log.w("EMBEDDING", `Failed to decode pre-generated embedding`, {
        entityId: e.id,
        name: e.name,
        error: (error as Error).message,
      });
      failedEntities.push(entity);
    }
  }

  if (vectorEmbeddings.length > 0) {
    const insertResult = await ctx.vectorStore.adaptiveBulkInsert(vectorEmbeddings);
    log.i("EMBEDDING", `Inserted pre-generated embeddings`, {
      count: vectorEmbeddings.length,
      timeMs: insertResult.timeMs.toFixed(1),
    });
    ctx.onMetricsUpdate(vectorEmbeddings.length);
  }

  return { processed: vectorEmbeddings.length, failed: failedEntities };
}

